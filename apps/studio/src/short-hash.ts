/*
 * Сокращение хэшей и длинных идентификаторов до читаемой формы.
 *
 * В репозитории исторически было ДВЕ расходящиеся по семантике копии, и они
 * намеренно сохранены раздельно — это не дубли, а разные форматы вывода:
 *
 *   shortHash     — префикс 7 символов (author-assistant.ts, app.ts):
 *                   "aaaaaaa…bbbbbb"; длина 14 и меньше отдаётся как есть.
 *   shortHashWide — префикс 8 символов (playtest-evidence.ts, portability.ts,
 *                   versions.ts): "aaaaaaaa…bbbbbb"; длина 14 и меньше — как есть.
 *
 * Порог сокращения у обеих функций один (>14 символов), различается только длина
 * префикса. Слияние в одну функцию изменило бы то, что автор видит в интерфейсе,
 * поэтому варианты не объединены.
 */

/** Короткая форма: 7 символов префикса, многоточие, 6 символов суффикса. */
export function shortHash(value: string): string {
  return value.length > 14 ? `${value.slice(0, 7)}…${value.slice(-6)}` : value;
}

/** Широкая форма: 8 символов префикса, многоточие, 6 символов суффикса. */
export function shortHashWide(value: string): string {
  return value.length <= 14 ? value : `${value.slice(0, 8)}…${value.slice(-6)}`;
}
